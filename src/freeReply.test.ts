import { describe, it, expect } from "vitest";
import source from "../stories/template/story.json";
import { compileStory } from "./story-engine/compiler";
import { initialRuntime } from "./schema";
import { dispatch, advance } from "./engine";
import { allChatsFree, sendFreeReply } from "./freeReply";
const {work} = compileStory(source);
describe("Left's confession continuation", () => {
  it("requires reads and manual sends and respects five- and three-second replies", () => {
    let s = initialRuntime(work);
    s.unlocked.push("interlude-call-zuo-3");
    s = dispatch(work,s,"send","interlude-calm-reply");
    expect(s.unlocked).not.toContain("interlude-calm-reply");
    s = dispatch(work,s,"read","interlude-call-zuo-3");
    s = dispatch(work,s,"send","interlude-calm-reply");
    s = advance(work,s,4999);
    expect(s.unlocked).not.toContain("interlude-secret");
    s = advance(work,s,1);
    expect(s.unlocked).toContain("interlude-secret");
    s = dispatch(work,s,"send","interlude-lovers-reply");
    expect(s.unlocked).not.toContain("interlude-lovers-reply");
    s = dispatch(work,s,"read","interlude-secret");
    s = dispatch(work,s,"send","interlude-lovers-reply");
    s = advance(work,s,2999);
    expect(s.unlocked).not.toContain("interlude-love-open");
    s = advance(work,s,1);
    expect(s.unlocked).toContain("interlude-love-open");
  });
  it("opens all six conversations only after reading the ending and friend branches", () => {
    let s = initialRuntime(work);
    s.read = ["interlude-love-final", "interlude-zhu-2"];
    expect(allChatsFree(s)).toBe(false);
    expect(sendFreeReply(work,s,"你好","妈咪")).toBe(s);
    s.read.push("interlude-zhang-2");
    expect(allChatsFree(s)).toBe(true);
    for (const name of ["A左左","妈咪","苏新皓","张峻豪","张泽禹","朱志鑫"]) {
      s = sendFreeReply(work,s,"你好",name);
      expect(s.messages.wechat.at(-1)?.title).toBe(name);
      expect(s.messages.wechat.at(-1)?.body).toBe("你好");
    }
    expect(sendFreeReply(work,s,"你好","未知联系人")).toBe(s);
  });
  it.each(["喜欢你", "我爱你"])("sends %s and replies only once after two seconds", text => {
    let s = initialRuntime(work);
    expect(sendFreeReply(work,s,text)).toBe(s);
    s.unlocked.push("interlude-love-open");
    expect(sendFreeReply(work,s,text)).toBe(s);
    s.read.push("interlude-love-open");
    expect(sendFreeReply(work,s,"  ")).toBe(s);
    s = sendFreeReply(work,s,"谢谢你");
    expect(s.messages.wechat.at(-1)?.body).toBe("谢谢你");
    expect(s.scheduled).toHaveLength(0);
    s = sendFreeReply(work,s,text);
    expect(s.messages.wechat.at(-1)?.outgoing).toBe(true);
    s = advance(work,s,1999);
    expect(s.unlocked).not.toContain("interlude-love-final");
    s = advance(work,s,1);
    expect(s.unlocked).toContain("interlude-love-final");
    expect(s.read).not.toContain("interlude-love-final");
    s = sendFreeReply(work,s,"喜欢你爱你");
    expect(s.scheduled?.filter(t => t.nodeId === "phone-free-love-delay")).toHaveLength(0);
  });
});

it("skips the first free message and counts any next three replies exactly once", () => {
 let s = initialRuntime(work);
 s.unlocked.push("interlude-love-open");s.read.push("interlude-love-open");
 s = sendFreeReply(work, s, "首条不计数");
 expect(s.variables.leftFreeMessageCount).toBe(0);
 s = sendFreeReply(work, s, "我爱你");
 expect(s.variables.leftFreeMessageCount).toBe(1);
 s = advance(work, s, 2000);
 expect(sendFreeReply(work, s, " ")).toBe(s);
 s = sendFreeReply(work, s, "喜欢你");
 expect(s.variables.leftFreeMessageCount).toBe(2);
 expect(s.scheduled).toHaveLength(0);
 s = sendFreeReply(work, s, "第三条");
 expect(s.variables.leftFreeMessageCount).toBe(3);
 expect(s.scheduled?.filter(t => t.nodeId === "left-busy-reply-delay")).toHaveLength(1);
 s = JSON.parse(JSON.stringify(s));
 s = advance(work, s, 1000);
 s = sendFreeReply(work, s, "第四条");
 s = advance(work, s, 2999);
 expect(s.unlocked).not.toContain("interlude-left-busy");
 s = advance(work, s, 1);
 expect(s.unlocked.filter(id => id === "interlude-left-busy")).toHaveLength(1);
 expect(work.data.wechat.find(i => i.id === "interlude-left-busy")?.body).toBe("刚刚在忙，不是故意不回你");
 s = sendFreeReply(work, s, "第五条");
 expect(s.scheduled?.filter(t => t.nodeId === "left-busy-reply-delay")).toHaveLength(0);
});
