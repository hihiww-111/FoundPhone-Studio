import { describe, it, expect } from "vitest";
import source from "../stories/template/story.json";
import { compileStory } from "./story-engine/compiler";
import { initialRuntime } from "./schema";
import { dispatch, advance } from "./engine";
import { sendFreeReply } from "./freeReply";
const {work} = compileStory(source);
describe("Left's confession continuation", () => {
  it("requires reads and manual sends and respects five- and three-second replies", () => {
    let s = initialRuntime(work);
    s.unlocked.push("interlude-call-zuo-3");
    s = dispatch(work,s,"send","interlude-calm-reply");
    expect(s.unlocked).not.toContain("interlude-calm-reply");
    s = dispatch(work,s,"read","interlude-call-zuo-3");
    s = dispatch(work,s,"send","interlude-calm-reply");
    s = advance(work,s,4999);
    expect(s.unlocked).not.toContain("interlude-secret");
    s = advance(work,s,1);
    expect(s.unlocked).toContain("interlude-secret");
    s = dispatch(work,s,"send","interlude-lovers-reply");
    expect(s.unlocked).not.toContain("interlude-lovers-reply");
    s = dispatch(work,s,"read","interlude-secret");
    s = dispatch(work,s,"send","interlude-lovers-reply");
    s = advance(work,s,2999);
    expect(s.unlocked).not.toContain("interlude-love-open");
    s = advance(work,s,1);
    expect(s.unlocked).toContain("interlude-love-open");
  });
  it.each(["喜欢你", "我爱你"])("sends %s and replies only once after two seconds", text => {
    let s = initialRuntime(work);
    expect(sendFreeReply(work,s,text)).toBe(s);
    s.unlocked.push("interlude-love-open");
    expect(sendFreeReply(work,s,text)).toBe(s);
    s.read.push("interlude-love-open");
    expect(sendFreeReply(work,s,"  ")).toBe(s);
    s = sendFreeReply(work,s,"谢谢你");
    expect(s.messages.wechat.at(-1)?.body).toBe("谢谢你");
    expect(s.scheduled).toHaveLength(0);
    s = sendFreeReply(work,s,text);
    expect(s.messages.wechat.at(-1)?.outgoing).toBe(true);
    s = advance(work,s,1999);
    expect(s.unlocked).not.toContain("interlude-love-final");
    s = advance(work,s,1);
    expect(s.unlocked).toContain("interlude-love-final");
    expect(s.read).not.toContain("interlude-love-final");
    s = sendFreeReply(work,s,"喜欢你爱你");
    expect(s.scheduled).toHaveLength(0);
  });
});
